"use client";

import { useCallback, useState } from "react";
import { FileDown } from "lucide-react";
import { Button } from "@/components/ui/button";
import { cn } from "@/lib/utils";
import { Textarea } from "@/components/ui/textarea";

type Props = {
  value: string;
  readOnly?: boolean;
};

export function EscrowJustification({ value, readOnly = true }: Props) {
  const [exporting, setExporting] = useState(false);

  const handleExportPdf = useCallback(async () => {
    setExporting(true);
    try {
      // Dynamic import keeps jspdf out of the initial bundle
      const { jsPDF } = await import("jspdf");

      const doc = new jsPDF({ unit: "pt", format: "a4" });

      const PAGE_W = doc.internal.pageSize.getWidth();
      const MARGIN = 48;
      const CONTENT_W = PAGE_W - MARGIN * 2;
      const LINE_H = 14;

      // ── Header ──────────────────────────────────────────────────────────
      doc.setFontSize(18);
      doc.setFont("helvetica", "bold");
      doc.text("Escrow Justification", MARGIN, 60);

      doc.setFontSize(9);
      doc.setFont("helvetica", "normal");
      doc.setTextColor(120);
      const exportedAt = new Date().toLocaleString(undefined, {
        dateStyle: "long",
        timeStyle: "short",
      });
      doc.text(`Exported: ${exportedAt}`, MARGIN, 78);

      // ── Divider ──────────────────────────────────────────────────────────
      doc.setDrawColor(200);
      doc.line(MARGIN, 88, PAGE_W - MARGIN, 88);

      // ── Body ─────────────────────────────────────────────────────────────
      doc.setFontSize(11);
      doc.setFont("helvetica", "normal");
      doc.setTextColor(30);

      const lines: string[] = doc.splitTextToSize(value ?? "", CONTENT_W);
      let y = 108;

      for (const line of lines) {
        if (y + LINE_H > doc.internal.pageSize.getHeight() - MARGIN) {
          doc.addPage();
          y = MARGIN + LINE_H;
        }
        doc.text(line, MARGIN, y);
        y += LINE_H;
      }

      // ── Footer ────────────────────────────────────────────────────────────
      doc.setFontSize(8);
      doc.setTextColor(160);
      doc.text(
        "Generated by TrueStub — trustless P2P ticket escrow on Stellar",
        MARGIN,
        doc.internal.pageSize.getHeight() - 24,
      );

      doc.save("escrow-justification.pdf");
    } finally {
      setExporting(false);
    }
  }, [value]);

  return (
    <div className="space-y-3">
      <div className="flex flex-col gap-2 sm:flex-row sm:items-start sm:justify-between">
        <h3 className="text-sm font-semibold text-foreground">
          Escrow justification
        </h3>
        <Button
          type="button"
          variant="outline"
          size="sm"
          onClick={handleExportPdf}
          disabled={exporting || !value}
          aria-label="Export justification as PDF"
          className={cn("gap-2", exporting && "opacity-70")}
        >
          <FileDown className="h-4 w-4" aria-hidden />
          {exporting ? "Exporting…" : "PDF"}
        </Button>
      </div>
      <Textarea
        readOnly={readOnly}
        defaultValue={value}
        className="min-h-[120px] resize-y bg-muted/30"
      />
    </div>
  );
}
